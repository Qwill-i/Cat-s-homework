def to_acronym(text):
    # разбиваем строку на слова по пробелу,
    # берём первую букву каждого слова, делаем заглавной и склеиваем
    return "".join(word[0].upper() for word in text.split(" "))

# text.split(" ") — разбивает строку на список слов по пробелам.
# word[0].upper() — берёт первый символ слова и делает его заглавным.
# "".join(...) — склеивает все полученные буквы в одну строку без разделителей.