def next_happy_year(year):
    year += 1                      # начинаем проверку со следующего года
    while True:
        if len(set(str(year))) == len(str(year)):  # все цифры уникальны?
            return year            # нашли счастливый год
        year += 1                  # иначе проверяем следующий

#В цикле проверяем: set(str(year)) убирает повторяющиеся цифры.
#Если длина множества совпадает с длиной строки года — значит, все цифры разные, и это счастливый год.